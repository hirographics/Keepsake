"""Writes app/sw.js with a precache list of every app file (not the big PSDs) and a content hash version."""
import hashlib, json, os
ROOT = "app"
files, h = [], hashlib.sha256()
for dp, dn, fn in os.walk(ROOT):
    dn.sort()
    for f in sorted(fn):
        p = os.path.join(dp, f)
        rel = os.path.relpath(p, ROOT).replace(os.sep, "/")
        if rel == "sw.js" or rel.endswith(".psd"):
            continue
        files.append(rel)
        h.update(rel.encode()); h.update(open(p, "rb").read())
files = ["./"] + [f for f in files if f != "index.html"] + ["index.html"]
ver = h.hexdigest()[:10]
open(os.path.join(ROOT, "sw.js"), "w").write(f"""// Generated by tools/build_sw.py. Keeps the app working with no internet.
const CACHE = 'keepsake-{ver}';
const FILES = {json.dumps(files)};
self.addEventListener('install', e => {{
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting()));
}});
self.addEventListener('activate', e => {{
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
}});
self.addEventListener('fetch', e => {{
  if (e.request.method !== 'GET') return;
  e.respondWith(caches.match(e.request, {{ ignoreSearch: true }}).then(hit => hit || fetch(e.request)));
}});
""")
print("sw", ver, len(files), "files")
